    items = [f'0x{b:02X}' for b in bs]
    if indent is None or len(items) <= 8:
        return '#[' + ', '.join(items) + ']'
    return '#[' + ', '.join(items[:8]) + ',\n' + indent + ', '.join(items[8:]) + ']'



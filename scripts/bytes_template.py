ORDER_DOC = {'LE': 'little-endian order, least significant byte first',
             'BE': 'big-endian order, most significant byte first'}


def shift(order, n, k):
    """The shift that brings byte `k` of an element into the low byte, in the given order."""
    s = 8 * (k if order == 'LE' else n - 1 - k)
    return s


def idx(n, k):
    return f'{n} * i' if k == 0 else f'{n} * i + {k}'


def uidx(k):
    return 'i' if k == 0 else f'(i + {k})'


def section(name, elem, u, n, to_u, of_u, swap):
    roundtrip = swap
    shows = ''.join(f'\n      show ({idx(n, k)}) / {n} = i by lia, show ({idx(n, k)}) % {n} = {k} by lia,'
                    for k in range(n)).rstrip(',')
    if of_u == '{}':
        finish = '    generalize s[i] = x\n    bv_decide'
    else:
        finish = (f'    conv => rhs; rw [← {elem}.to{elem}_to{u} s[i]]\n'
                  f'    congr 1\n    generalize s[i].to{u} = x\n    bv_decide')
    A = name + 'Array'
    out = [f'\nnamespace {A}\n']
    push_arg = 'u' if of_u == '{}' else '(' + of_u.format('u') + ')'
    wrap = of_u != '{}'
    for order in ['LE', 'BE']:
        doc = ORDER_DOC[order]
        if order == 'LE':
            spec_shift = f'8 * (j % {n})'
        else:
            spec_shift = f'8 * ({n - 1} - j % {n})'
        byte = to_u.format('s[j / ' + str(n) + ']')
        stores = ''.join(
            f'\n        |>.setUnsafe (j + {k}) (u >>> {shift(order, n, k)}).toUInt8' if k else
            f'\n        |>.setUnsafe j (u >>> {shift(order, n, 0)}).toUInt8'
            for k in range(n))
        stores = stores.replace('(u >>> 0).toUInt8', 'u.toUInt8')
        combine = ' |||\n        '.join(
            (f'(b[{idx(n, k)}]\'(by lia)).to{u}' if shift(order, n, k) == 0 else
             f'((b[{idx(n, k)}]\'(by lia)).to{u} <<< {shift(order, n, k)})')
            for k in range(n))
        combine_impl = ' |||\n          '.join(
            (f'(b.uget {uidx(k)} lcProof).to{u}' if shift(order, n, k) == 0 else
             f'((b.uget {uidx(k)} lcProof).to{u} <<< {shift(order, n, k)})')
            for k in range(n))
        out.append(f'''
private unsafe def Slice.toBytes{order}Impl (s : {A}.Slice) : ByteArray :=
  (loop s.array s.stop.toUSize (UInt8Array.replicate ({n} * s.size) 0) s.start.toUSize 0).toByteArray
where
  loop (a : {A}) (stop : USize) (r : UInt8Array) (i j : USize) : UInt8Array :=
    if i < stop then
      let u := {to_u.format('(a.uget i lcProof)')}
      -- `r` is a fresh array, so the stores need no exclusivity checks, and they combine into one
      -- word store.
      loop a stop (r{stores}) (i + 1) (j + {n})
    else
      r

/-- The elements of `s` as bytes, each in {doc}. -/
@[implemented_by Slice.toBytes{order}Impl, expose]
public def Slice.toBytes{order} (s : {A}.Slice) : ByteArray :=
  ⟨Array.ofFn (n := {n} * s.size) fun ⟨j, hj⟩ =>
    ({to_u.format(f"(s[j / {n}]'(by lia))")} >>> ({spec_shift}).to{u}).toUInt8⟩

/-- The elements of `a` as bytes, each in {doc}. -/
@[inline, expose]
public def toBytes{order} (a : {A}) : ByteArray := a.toSlice.toBytes{order}

private unsafe def ofBytes{order}?Impl (b : ByteArray) : Option {A} :=
  if b.size % {n} = 0 then some (loop (emptyWithCapacity (b.size / {n})) 0) else none
where
  loop (r : {A}) (i : USize) : {A} :=
    if i < b.usize then
      let u :=
          {combine_impl}
      loop (r.push {push_arg}) (i + {n})
    else
      r

/--
Reads `b` as elements, each in {doc}.
Returns `none` if the size of `b` is not a multiple of {n}.
-/
@[implemented_by ofBytes{order}?Impl, expose]
public def ofBytes{order}? (b : ByteArray) : Option {A} :=
  if b.size % {n} = 0 then
    some <| ofFn (n := b.size / {n}) fun ⟨i, hi⟩ =>
      {of_u.format('(' + combine + ')') if wrap else combine}
  else
    none

/--
Reads `b` as elements, each in {doc}.
Panics if the size of `b` is not a multiple of {n}.
-/
public def ofBytes{order}! (b : ByteArray) : {A} :=
  match ofBytes{order}? b with
  | some a => a
  | none => panic! "byte array size is not a multiple of {n}"

@[simp] public theorem Slice.size_toBytes{order} (s : {A}.Slice) :
    s.toBytes{order}.size = {n} * s.size := by
  simp [Slice.toBytes{order}, ← ByteArray.size_data]

@[simp] public theorem size_toBytes{order} (a : {A}) : a.toBytes{order}.size = {n} * a.size := by
  simp [toBytes{order}]

@[simp] public theorem Slice.getElem_toBytes{order} (s : {A}.Slice) (j : Nat)
    (h : j < s.toBytes{order}.size) :
    s.toBytes{order}[j] =
      ({to_u.format(f"(s[j / {n}]'(by rw [Slice.size_toBytes{order}] at h; lia))")} >>> ({spec_shift}).to{u}).toUInt8 := by
  simp only [Slice.toBytes{order}, ByteArray.getElem_eq_getElem_data, Array.getElem_ofFn]
''')
        if roundtrip:
            out.append(f'''
@[simp] public theorem ofBytes{order}?_toBytes{order}_slice (s : {A}.Slice) :
    ofBytes{order}? s.toBytes{order} = some s.copy := by
  rw [ofBytes{order}?, ite_eq_left_of_eq_true _ _ (by simp)]
  congr 1
  apply ext_getElem
  · simp
  · intro i _ h
    have hi : i < s.size := by simpa using h
    simp only [getElem_ofFn, Slice.getElem_toBytes{order}, Slice.getElem_copy,{shows}]
    simp only [Nat.reduceMul,{' Nat.reduceSub,' if order == 'BE' else ''} Nat.to{u},
      {u}.reduceOfNat]
{finish}

@[simp] public theorem ofBytes{order}?_toBytes{order} (a : {A}) :
    ofBytes{order}? a.toBytes{order} = some a := by
  simp [toBytes{order}]
''')
    if swap:
        out.append(f'''
private unsafe def byteSwapImpl (a : {A}) : {A} :=
  a.foldInPlaceThen 0 a.usize () (fun _ _ x _ => (x.byteSwap, ())) (fun a _ => a) lcProof

/-- Reverses the order of the bytes of each element, in place when `a` is not shared. -/
@[implemented_by byteSwapImpl, expose]
public def byteSwap (a : {A}) : {A} :=
  mk (a.data.map {elem}.byteSwap)

@[simp] public theorem data_byteSwap (a : {A}) : a.byteSwap.data = a.data.map {elem}.byteSwap :=
  rfl

@[simp] public theorem size_byteSwap (a : {A}) : a.byteSwap.size = a.size := by
  simp [← size_data]

@[simp] public theorem getElem_byteSwap (a : {A}) (i : Nat) (h : i < a.byteSwap.size) :
    a.byteSwap[i] = (a[i]'(by simpa using h)).byteSwap := by
  rw [getElem_eq_getElem_data, getElem_eq_getElem_data]
  simp

@[simp] public theorem byteSwap_byteSwap (a : {A}) : a.byteSwap.byteSwap = a := by
  apply ext_getElem <;> simp
''')
    out.append(f'\nend {A}\n')
    return ''.join(out)


def module():
    return HEADER + ''.join(section(*t) for t in types) + FOOTER


